#Arithmetic operator
# + - Addition
# - - Subtraction
# * - Multiplication
# / - division
# // - floor division
# ** - exponentation
# % - modulus 

a = 21
b = 18

sum = a + b
difference = a - b
product = a * b
quotient = a / b
floorquotient = a // b
exponent = a ** b
modulus = a % b

print("The sum of ", a, "and", b, "is", sum)
print("The difference of", a, "and", b, "is", difference)
print("The product of", a, "and", b, "is", product)
print("The quotient of", a, "and", b, "is", quotient)
print("The floor quotient of" ,a, "and", b, "is", floorquotient)
print("The exponential value of", a, "and",b, "is", exponent)
print("The remainder of",a, "and", b, "is", modulus)





